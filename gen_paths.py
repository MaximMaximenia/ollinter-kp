def act(a):
    if a.startswith('!'): return '<li class="bad">%s</li>'%a[1:]
    if a.startswith('*'): return '<li class="flag">%s</li>'%a[1:]
    return '<li>%s</li>'%a

def visit(v):
    cls,lab = v['badge']
    rows=[]
    for i,(kind,page,acts) in enumerate(v['steps'],1):
        rows.append('''<div class="st">
  <div class="dot">%d</div>
  <div class="stb">
    <div class="pg"><span class="kind">%s</span><span class="pname">%s</span></div>
    <ul class="acts">%s</ul>
  </div>
</div>'''%(i,kind,page,''.join(act(a) for a in acts)))
    return '''<section class="visit %s">
<div class="vh"><span class="vn">Заход %d</span><h3>%s</h3><span class="bdg %s">%s</span></div>
<div class="who">%s</div>
<div class="track">%s</div>
</section>'''%(cls,v['n'],v['t'],cls,lab,v['who'],''.join(rows))

